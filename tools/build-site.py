_dims = {}


def dims(rel):
    if rel not in _dims:
        out = subprocess.run(["sips", "-g", "pixelWidth", "-g", "pixelHeight", str(ROOT / rel)],
                             capture_output=True, text=True).stdout.split()
        _dims[rel] = (round(float(out[-3])), round(float(out[-1])))
    return _dims[rel]


def variant(rel, w):
    p = pathlib.Path(rel)
    return "/images/_r/" + str(p.relative_to("images").with_suffix("")) + f"-{w}.jpg"


def img(src, alt, sizes="(max-width: 760px) 100vw, 50vw", eager=False, zoom=False, cls=""):
    if not (ROOT / src).exists():
        raise SystemExit(f"missing image: {src}")
    w, h = dims(src)
    a = html.escape(alt, quote=True)
    load = 'fetchpriority="high"' if eager else 'loading="lazy"'
    if src.endswith(".jpg"):
        s = f'src="{variant(src, 800)}" srcset="{variant(src, 800)} 800w, {variant(src, 1600)} 1600w" sizes="{sizes}"'
    else:
        s = f'src="/{src}"'
    c = f' class="{cls}"' if cls else ""
    tag = f'<img {s} alt="{a}" width="{w}" height="{h}" {load} decoding="async"{c}>'
    if zoom:
        full = variant(src, 1600) if src.endswith(".jpg") else "/" + src
        return f'<button type="button" class="zoom" data-full="{full}" data-alt="{a}" aria-label="Enlarge: {a}">{tag}</button>'
    return tag


