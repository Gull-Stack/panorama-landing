# A content hash, so a CSS or JS change is never hidden by the one-year
# immutable cache vercel.json puts on /css and /js. ⛔ EVERY local css/js file
# a page loads must carry it: near-map.js shipped without one on 10/29 and a
# returning browser kept the old map, schools and all.
def _version():
    import hashlib
    h = hashlib.sha1()
    for f in ("css/site.css", "js/site.js", "js/near-map.js"):
        h.update((ROOT / f).read_bytes())
    return h.hexdigest()[:8]


VERSION = _version()

SHORT = re.compile(r"\{\{(\w+)((?:\s+[\w-]+(?:=\"[^\"]*\")?)*)\s*\}\}")
ATTR = re.compile(r'([\w-]+)(?:="([^"]*)")?')


def expand(body):
    def one(m):
        name, raw = m.group(1), m.group(2)
        a = {k: (v if v is not None else True) for k, v in ATTR.findall(raw)}
        a = {k: (True if v == "" and k in ("eager", "zoom") else v) for k, v in a.items()}
        if name == "img":
            return img(a["src"], a.get("alt", ""), a.get("sizes", "(max-width: 760px) 100vw, 50vw"),
                       eager="eager" in a, zoom="zoom" in a, cls=a.get("class", ""))
        if name == "builders":
            return builder_grid()
        if name == "gallery":
            # Small copies in the grid, the large copy only when opened.
            shots = sorted((ROOT / "images" / "aerial").glob("*.jpg"))
            return '<div class="gallery">' + "".join(
                img(f"images/aerial/{s.name}", f"Panorama aerial view {i}", sizes="(max-width: 700px) 100vw, 33vw", zoom=True)
                for i, s in enumerate(shots, 1)) + "</div>"
        if name == "homesites":
            return homesites(a["phase"])
        if name == "soon":
            return soon(a["title"], a["text"])
        raise SystemExit(f"unknown shortcode {{{{{name}}}}}")
    return SHORT.sub(one, body)


def out_path(url):
    if url == "/":
        return ROOT / "index.html"
    p = url.strip("/")
    return ROOT / (p + ".html") if p in ("gallery",) or "/" in p else ROOT / p / "index.html"


def render_all():
    files = {}
    for src in sorted(SRC.glob("*.html")):
        text = src.read_text()
        first, _, body = text.partition("\n")
        meta = json.loads(first.removeprefix("<!--page").removesuffix("-->").strip())
        files[out_path(meta["url"])] = page(meta, expand(body), "src/pages/" + src.name)
    for b in builders():
        meta = {"url": f"/find-a-home/builder-{b['slug']}",
                "title": f"{b['name']} at Panorama | Herriman, Utah",
                "description": (b.get("intro") or f"{b['name']} is building {(b.get('productType') or 'homes').lower()} at Panorama, Herriman's foothills community.")[:300],
                "nav": "find", "image": (b.get("exteriorImages") or ["images/aerial/aerial-01.jpg"])[0]}
        files[out_path(meta["url"])] = page(meta, builder_body(b), "data/builders.json")
    return files


def main():
    check = "--check" in sys.argv
    stale = []
    for path, text in render_all().items():
        if not path.exists() or path.read_text() != text:
            stale.append(path.relative_to(ROOT))
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text)
    if check and stale:
        print("STALE - run ./tools/build.sh:", *stale, sep="\n  ")
        return 1
    print(f"{'wrote' if stale else 'pages are current'}" + (f" {len(stale)} pages" if stale else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
